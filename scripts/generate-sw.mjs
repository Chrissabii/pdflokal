// Runs after `next build`: writes out/sw.js, a service worker that precaches the whole exported app
// so it can be installed and used without a server or internet connection.
// - "core" (pages, JS/CSS, fonts, images): cached on install → all PDF tools work offline immediately
// - "heavy" (ONNX Runtime for translation, Tesseract OCR): cached right after, in the background
// Translation models themselves are cached by transformers.js (Cache Storage) on first use / download.
import { createHash } from "node:crypto";
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative, sep } from "node:path";

const OUT = "out";
// Must match next.config.ts (GitHub Pages project sites are served from /<repo>/).
const BASE = (process.env.NEXT_PUBLIC_BASE_PATH ?? "").replace(/\/+$/, "");

function walk(dir) {
  return readdirSync(dir).flatMap((name) => {
    const path = join(dir, name);
    return statSync(path).isDirectory() ? walk(path) : [path];
  });
}

const files = walk(OUT)
  .map((p) => "/" + relative(OUT, p).split(sep).join("/"))
  .filter((url) => url !== "/sw.js" && url !== "/.nojekyll" && !url.endsWith(".map"))
  .sort();

// The bundler also emits a copy of the ONNX Runtime .wasm under _next/static/media; treat all .wasm as heavy.
const isHeavy = (url) => url.startsWith("/ort/") || url.startsWith("/tesseract/") || url.endsWith(".wasm");
// Pages are requested as "/route/" — cache them under that URL instead of ".../index.html".
const toUrl = (file) => (file.endsWith("/index.html") ? file.slice(0, -"index.html".length) : file);

const coreFiles = files.filter((f) => !isHeavy(f)).map(toUrl);
const heavyFiles = files.filter(isHeavy);
const core = coreFiles.map((f) => BASE + f);
const heavy = heavyFiles.map((f) => BASE + f);

const hash = (list) => {
  const h = createHash("sha256");
  for (const f of list) h.update(f).update(readFileSync(join(OUT, f.endsWith("/") ? f + "index.html" : f)));
  return h.digest("hex").slice(0, 12);
};

const sw = `// Generated by scripts/generate-sw.mjs — do not edit.
const CORE_CACHE = "core-${hash(coreFiles)}";
const HEAVY_CACHE = "heavy-${hash(heavyFiles)}";
const BASE = ${JSON.stringify(BASE)};
const CORE = ${JSON.stringify(core)};
const HEAVY = ${JSON.stringify(heavy)};

self.addEventListener("install", (event) => {
  event.waitUntil(caches.open(CORE_CACHE).then((cache) => cache.addAll(CORE)).then(() => self.skipWaiting()));
});

async function broadcast(message) {
  for (const client of await self.clients.matchAll({ includeUncontrolled: true })) client.postMessage(message);
}

async function cacheHeavy() {
  const cache = await caches.open(HEAVY_CACHE);
  const missing = [];
  for (const url of HEAVY) if (!(await cache.match(url))) missing.push(url);
  let done = HEAVY.length - missing.length;
  await broadcast({ type: "offline-progress", done, total: HEAVY.length });
  for (const url of missing) {
    try {
      await cache.add(url);
    } catch {
      // retried on the next start; the app still works online meanwhile
    }
    done++;
    await broadcast({ type: "offline-progress", done, total: HEAVY.length });
  }
}

self.addEventListener("activate", (event) => {
  event.waitUntil(
    (async () => {
      for (const key of await caches.keys()) {
        if ((key.startsWith("core-") && key !== CORE_CACHE) || (key.startsWith("heavy-") && key !== HEAVY_CACHE)) {
          await caches.delete(key);
        }
      }
      await self.clients.claim();
      await cacheHeavy();
    })(),
  );
});

self.addEventListener("message", (event) => {
  if (event.data === "offline-status") event.waitUntil(cacheHeavy());
});

self.addEventListener("fetch", (event) => {
  const request = event.request;
  const url = new URL(request.url);
  if (request.method !== "GET" || url.origin !== self.location.origin) return;
  event.respondWith(
    (async () => {
      // ignoreSearch: Next.js adds ?_rsc=… to client-navigation payloads
      let response = await caches.match(request, { ignoreSearch: true });
      if (!response && request.mode === "navigate") {
        response = await caches.match(url.pathname.endsWith("/") ? url.pathname : url.pathname + "/");
      }
      if (!response) {
        try {
          response = await fetch(request);
        } catch (err) {
          if (request.mode !== "navigate") throw err;
          response = await caches.match(BASE + "/");
          if (!response) throw err;
        }
      }
      return isolate(response);
    })(),
  );
});

// Re-wraps a same-origin response:
// - adds COOP/COEP so the page is cross-origin isolated → SharedArrayBuffer → multi-threaded translation
// - drops the response URL: a worker takes its location from it, and Turbopack's worker bootstrap reads
//   its config from ?params=… in that location (a cached copy is stored without the query)
function isolate(response) {
  if (!response || response.status === 0) return response;
  const headers = new Headers(response.headers);
  headers.set("Cross-Origin-Opener-Policy", "same-origin");
  headers.set("Cross-Origin-Embedder-Policy", "require-corp");
  headers.set("Cross-Origin-Resource-Policy", "same-origin");
  return new Response(response.body, { status: response.status, statusText: response.statusText, headers });
}
`;

writeFileSync(join(OUT, "sw.js"), sw);
// GitHub Pages runs Jekyll by default, which drops folders starting with "_" (like _next/).
writeFileSync(join(OUT, ".nojekyll"), "");
const size = (list) =>
  (list.reduce((n, f) => n + statSync(join(OUT, f.endsWith("/") ? f + "index.html" : f)).size, 0) / 1024 / 1024).toFixed(1);
console.log(`sw.js${BASE ? ` (base ${BASE})` : ""}: ${core.length} core files (${size(coreFiles)} MB), ${heavy.length} offline-pack files (${size(heavyFiles)} MB)`);
